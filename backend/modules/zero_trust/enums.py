"""Stable identifiers used by Zero Trust domain models."""

from enum import StrEnum


class AccessDecision(StrEnum):
    ALLOW = "ALLOW"
    REQUEST_VERIFICATION = "REQUEST_VERIFICATION"
    DENY = "DENY"


class VerificationModule(StrEnum):
    FACE_RECOGNITION = "FACE_RECOGNITION"
    FACE_LIVENESS = "FACE_LIVENESS"
    FINGERPRINT = "FINGERPRINT"
    RFID = "RFID"


class EvidenceOutcome(StrEnum):
    SUCCESS = "SUCCESS"
    FAILURE = "FAILURE"
    PENDING = "PENDING"
    EXPIRED = "EXPIRED"
    INDETERMINATE = "INDETERMINATE"
    ERROR = "ERROR"


class ResourceSensitivity(StrEnum):
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class RecordStatus(StrEnum):
    ACTIVE = "ACTIVE"
    INACTIVE = "INACTIVE"
    SUSPENDED = "SUSPENDED"
    REVOKED = "REVOKED"
    EXPIRED = "EXPIRED"


class PermissionEffect(StrEnum):
    GRANT = "GRANT"
    DENY = "DENY"


class RevocationState(StrEnum):
    CLEAR = "CLEAR"
    REVOKED = "REVOKED"


class DecisionReasonCode(StrEnum):
    ACCESS_POLICY_SATISFIED = "ACCESS_POLICY_SATISFIED"
    PERMISSION_DENIED = "PERMISSION_DENIED"
    PERMISSION_NOT_FOUND = "PERMISSION_NOT_FOUND"
    IDENTITY_UNVERIFIED = "IDENTITY_UNVERIFIED"
    IDENTITY_MISMATCH = "IDENTITY_MISMATCH"
    IDENTITY_SUSPENDED = "IDENTITY_SUSPENDED"
    IDENTITY_REVOKED = "IDENTITY_REVOKED"
    CONFIRMED_SPOOF = "CONFIRMED_SPOOF"
    EVIDENCE_PENDING = "EVIDENCE_PENDING"
    EVIDENCE_EXPIRED = "EVIDENCE_EXPIRED"
    EVIDENCE_INVALID = "EVIDENCE_INVALID"
    EVIDENCE_PROVIDER_UNAVAILABLE = "EVIDENCE_PROVIDER_UNAVAILABLE"
    RECORD_CONFLICT = "RECORD_CONFLICT"
    RECORD_STALE = "RECORD_STALE"
    AUTHORIZATION_DATA_UNAVAILABLE = "AUTHORIZATION_DATA_UNAVAILABLE"
    REVOCATION_STALE = "REVOCATION_STALE"
    REVOCATION_UNAVAILABLE = "REVOCATION_UNAVAILABLE"
    EXAM_NOT_ELIGIBLE = "EXAM_NOT_ELIGIBLE"
    OUTSIDE_EXAM_SCHEDULE = "OUTSIDE_EXAM_SCHEDULE"
    LAB_SAFETY_CLEARANCE_REQUIRED = "LAB_SAFETY_CLEARANCE_REQUIRED"
    TEMPORARY_PASS_INVALID = "TEMPORARY_PASS_INVALID"
    POLICY_REQUIREMENTS_UNMET = "POLICY_REQUIREMENTS_UNMET"


AccessReasonCode = DecisionReasonCode
